pub(crate) fn chinese(word: &str) -> &str {
    WORDS
        .iter()
        .find(|(english, _)| *english == word)
        .map(|(_, chinese)| *chinese)
        .unwrap_or(word)
}
pub(crate) fn english(word: &str) -> &str {
    WORDS
        .iter()
        .find(|(_, chinese)| *chinese == word)
        .map(|(english, _)| *english)
        .unwrap_or(word)
}
